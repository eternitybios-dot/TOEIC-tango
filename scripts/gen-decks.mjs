function pack(id0, rows) {
  const per = Math.ceil(rows.length / 3);
  return rows.map((row, i) => {
    const unit = Math.min(3, Math.floor(i / per) + 1);
    const part = unit;
    const [word, pos, meaning, phrase, phraseJa] = row;
    return { id: id0 + i, word, ipa: "", pos, meaning, phrase, phraseJa, part, unit };
  });
}

