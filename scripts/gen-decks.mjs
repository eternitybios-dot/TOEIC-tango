function unique(words, name) {
  const ids = new Set();
  const heads = new Set();
  for (const word of words) {
    if (ids.has(word.id)) throw new Error(`${name} duplicate id ${word.id}`);
    if (heads.has(word.word.toLowerCase())) throw new Error(`${name} duplicate ${word.word}`);
    ids.add(word.id);
    heads.add(word.word.toLowerCase());
  }
}

