def _ok(row: tuple[str, str, str, str, str]) -> bool:
    w, pos, meaning, phrase, phrase_ja = row
    if pos not in {"名", "動", "形", "副", "前", "接", "句"}:
        return False
    if any("\t" in x or not x.strip() for x in row):
        return False
    n = len(phrase.split())
    if not 2 <= n <= 5:
        return False
    if w.lower() not in phrase.lower():
        return False
    return True


def build() -> list[tuple[str, str, str, str, str]]:
    seen: set[str] = set()
    rows: list[tuple[str, str, str, str, str]] = []

    def add(src: list[tuple[str, str, str, str, str]], skip_elem: bool = False) -> None:
        for row in src:
            key = row[0].lower()
            if key in seen:
                continue
            if skip_elem and key in ELEMENTARY:
                continue
            if not _ok(row):
                raise SystemExit(f"bad row: {row!r}")
            seen.add(key)
            rows.append(row)

    add(KISO, skip_elem=True)
    add(FILL)
    add(HATTEN_EXTRA)
    return rows


