def split_bands(rows: list[tuple[str, str, str, str, str]]) -> list[tuple[str, str, str, str, str]]:
    """Keep original insertion order: high-frequency KISO first, hard extras last."""
    if len(rows) < 1900:
        raise SystemExit(f"only {len(rows)} unique rows, need 1900")

    kiso = rows[:800]
    hisshu = rows[800:1500]
    used = {r[0].lower() for r in kiso + hisshu}
    hatten: list[tuple[str, str, str, str, str]] = []
    for r in HATTEN_EXTRA:
        k = r[0].lower()
        if k in used:
            continue
        hatten.append(r)
        used.add(k)
        if len(hatten) == 400:
            break
    if len(hatten) < 400:
        for r in rows:
            k = r[0].lower()
            if k in used:
                continue
            hatten.append(r)
            used.add(k)
            if len(hatten) == 400:
                break

    out = kiso + hisshu + hatten
    if len(kiso) != 800 or len(hisshu) != 700 or len(hatten) != 400:
        raise SystemExit(f"band sizes {len(kiso)}/{len(hisshu)}/{len(hatten)}")
    keys = [r[0].lower() for r in out]
    if len(out) != 1900 or len(keys) != len(set(keys)):
        raise SystemExit(f"split produced {len(out)} unique {len(set(keys))}")
    return out


